"""Build the portable GF64-tower change of basis from the consensus constants."""

from pathlib import Path

from generate import apply_basis, gf_product, pair
from generate_aes_tables import load_array

# Canonical flat representations of the two generators.
X = 0x0C0C7406064693737C30B4F1073046CD
Y = 0x048528203BBBAD2771754DEE8D563590


def inverse_columns(columns):
    rows = [
        sum(((column >> i) & 1) << j for j, column in enumerate(columns)) | (1 << (128 + i))
        for i in range(128)
    ]
    for i in range(128):
        pivot = next(j for j in range(i, 128) if (rows[j] >> i) & 1)
        rows[i], rows[pivot] = rows[pivot], rows[i]
        for j in range(128):
            if j != i and (rows[j] >> i) & 1:
                rows[j] ^= rows[i]
    return [sum(((row >> (i + 128)) & 1) << j for j, row in enumerate(rows)) for i in range(128)]


def emit_array(name, columns):
    return f"static const uint64_t {name}[128][2] = {{\n    " + ",\n    ".join(map(pair, columns)) + "\n};\n"


def main():
    public_tables = Path(__file__).with_name("noid_tables.h").read_text()
    consensus_to_flat = load_array(public_tables, "noid_tower_to_flat")
    flat_to_consensus = load_array(public_tables, "noid_flat_to_tower")
    powers = [1]
    for i in range(64):
        powers.append(gf_product(powers[-1], X))
    assert powers[64] == powers[4] ^ powers[3] ^ powers[1] ^ powers[0]
    assert gf_product(Y, Y) == gf_product(X, Y) ^ X
    tower_to_flat = powers[:64] + [gf_product(power, Y) for power in powers[:64]]
    flat_to_tower = inverse_columns(tower_to_flat)
    assert all(apply_basis(flat_to_tower, col) == 1 << i for i, col in enumerate(tower_to_flat))

    partial = load_array(public_tables, "noid_mds_partial")
    fixed = [partial[5 * i] ^ 1 for i in range(4)] + consensus_to_flat[1:3]
    if any(apply_basis(flat_to_tower, coefficient) >> 64 for coefficient in fixed):
        raise ValueError("The accelerated matrix coefficients must lie in the GF(2^64) subfield")
    print("/* SPDX-License-Identifier: Apache-2.0 */")
    print("/* Generated by generate_gf64_tables.py. */")
    print(emit_array("noid_flat_to_tower64", flat_to_tower), end="")
    print(emit_array("noid_tower_to_tower64", [apply_basis(flat_to_tower, col) for col in consensus_to_flat]), end="")
    print(emit_array("noid_tower64_to_tower", [apply_basis(flat_to_consensus, col) for col in tower_to_flat]), end="")


if __name__ == "__main__":
    main()
